#!/usr/bin/env bash
# Regenerate core/src/upstream_verbatim.rs (zk-Analytics' private functions, cut verbatim from d4a5a9a) or --check it.
# Usage: ./gen_upstream.sh [--check]
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../common.sh"   # ZKA
HLL="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HLL/core/src/upstream_verbatim.rs"
REV=d4a5a9a
got=$(git -C "$ZKA" rev-parse --short=7 HEAD)
[[ $got == "$REV" ]] || { echo "clone is at $got, expected $REV" >&2; exit 2; }

A=aggregator/core/src/lib.rs
Q=querier/core/src/lib.rs
# file first last what
BLOCKS=(
  "$A 57 57 TAG_SHARD_CHAIN (used in verify_and_compute_chain's panic message)"
  "$A 93 99 sha256_bytes"
  "$A 295 305 events_commit"
  "$A 331 339 chain_tips_to_sorted_vec"
  "$A 499 603 verify_and_compute_chain (source batch hash-chain verification)"
  "$Q 41 41 TAG_EPOCH_CHAIN (querier copy)"
  "$Q 98 136 verify_epoch_chain_integrity (query-side epoch chain-link checks)"
)

gen() {
  echo "// GENERATED by gen_upstream.sh -- do not edit. Verbatim copies from zk-Analytics"
  echo "// (https://github.com/Froot-NetSys/zk-Analytics, commit $REV); each block is preceded by"
  echo "// its source file and line range."
  for b in "${BLOCKS[@]}"; do
    read -r f s e what <<< "$b"
    echo
    echo "// ---- upstream $f:$s-$e @ $REV -- $what"
    sed -n "${s},${e}p" "$ZKA/$f"
  done
}

if [[ ${1:-} == --check ]]; then
  if diff -u <(gen) "$OUT"; then echo "upstream_verbatim.rs matches $ZKA @ $REV"; else echo "MISMATCH" >&2; exit 1; fi
else
  gen > "$OUT"
  echo "wrote $OUT"
fi
