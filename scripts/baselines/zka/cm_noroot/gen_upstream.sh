#!/usr/bin/env bash
# Writes core/src/upstream_{noroot,twin}.rs from the zk-Analytics clone at d4a5a9a (--check: diff only).
# Usage: ./gen_upstream.sh [--check]
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../common.sh"   # ZKA
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REV=d4a5a9a
got=$(git -C "$ZKA" rev-parse --short=7 HEAD)
[[ $got == "$REV" ]] || { echo "clone is at $got, expected $REV" >&2; exit 2; }
A=aggregator/core/src/lib.rs

# file first last what
COMMON=(
  "$A 48 48 TAG_CM_STATE_COMMIT"
  "$A 56 57 TAG_SHARD_CHAIN"
  "$A 93 99 sha256_bytes"
  "$A 295 305 events_commit"
  "$A 307 313 batch_chain_hash"
  "$A 331 339 chain_tips_to_sorted_vec"
  "$A 341 350 key_to_u64"
  "$A 499 603 verify_and_compute_chain (source batch hash-chain verification)"
  "$A 1055 1064 cm_bucket_index"
  "$A 1090 1101 cm_estimate_count"
  "$A 1103 1141 cm_heap_update"
  "$A 1182 1208 cm_state_commit"
  "$A 1210 1213 process_cm_aggr"
)
TWIN_ONLY=(
  "$A 50 51 TAG_CM_LEAF, TAG_CM_HEAP_LEAF"
  "$A 82 91 next_pow2_ge"
  "$A 1066 1073 cm_leaf_hash"
  "$A 1075 1088 cm_row_root"
  "$A 1143 1151 cm_heap_leaf_hash"
  "$A 1153 1180 cm_heap_root"
)

header() {  # header <what>
  echo "// GENERATED by ../../gen_upstream.sh -- do not edit. Verbatim copies from zk-Analytics"
  echo "// (https://github.com/Froot-NetSys/zk-Analytics, commit $REV); each block is preceded by"
  echo "// its source file and line range. $1"
}
block() {  # block "<file> <first> <last> <what>"
  local f s e what
  read -r f s e what <<< "$1"
  echo
  echo "// ---- upstream $f:$s-$e @ $REV -- $what"
  sed -n "${s},${e}p" "$ZKA/$f"
}

gen_noroot() {
  local b
  header "The one edit is the block marked NOROOT."
  for b in "${COMMON[@]}"; do block "$b"; done
  echo
  echo "// ---- upstream $A:1215-1301 @ $REV -- process_cm_aggr_with_state, lines 1262-1274 replaced (NOROOT)"
  sed -n '1215,1261p' "$ZKA/$A"
  cat <<'EOF'
    // ---- NOROOT (ours; replaces upstream lines 1262-1274) -------------------------------
    // Upstream computes row_roots (one SHA-256 leaf per counter, folded per row by their
    // MerkleTree), cm_root (a MerkleTree over the 3 row roots) and heap_root (a MerkleTree
    // over the top-k heap slots) here. No query guest or verifier reads them; their host
    // only folds them into an out_commit kept in its database. They are not computed: the
    // journal carries zeros. Everything before and after this block is upstream, verbatim.
    let row_roots = [[0u8; HASH_BYTES_LEN]; CM_ROWS];
    let cm_root = [0u8; HASH_BYTES_LEN];
    let heap_root = [0u8; HASH_BYTES_LEN];
    // ---- end NOROOT ----------------------------------------------------------------------
EOF
  sed -n '1275,1301p' "$ZKA/$A"
}

gen_twin() {
  local b
  header "Nothing is edited (validation twin of their aggr_cm)."
  for b in "${COMMON[@]}" "${TWIN_ONLY[@]}"; do block "$b"; done
  block "$A 1215 1301 process_cm_aggr_with_state (whole, unedited)"
}

OUT_N="$DIR/core/src/upstream_noroot.rs"
OUT_T="$DIR/core/src/upstream_twin.rs"
if [[ ${1:-} == --check ]]; then
  rc=0
  diff -u <(gen_noroot) "$OUT_N" || rc=1
  diff -u <(gen_twin) "$OUT_T" || rc=1
  if (( rc == 0 )); then echo "upstream_noroot.rs and upstream_twin.rs match $ZKA @ $REV"; else echo "MISMATCH" >&2; exit 1; fi
else
  gen_noroot > "$OUT_N"
  gen_twin > "$OUT_T"
  echo "wrote $OUT_N $OUT_T"
fi
